  readonly flights$ = new BehaviorSubject<Flight[]>(flights);
  readonly selected$ = new BehaviorSubject<Flight>(flights[0]);
  select(f: Flight) {
    this.selected$.next(f);
  }
  update(flights: Flight[]) {
    this.flights$.next(flights);
    const selected = flights.find((f) => f.id === this.selected$.value.id);
    if (selected) this.selected$.next(selected);
  }
